import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';

const result = spawnSync(
  'supabase',
  [
    'status',
    '--workdir', '../..',
    '-o', 'env',
    '--override-name', 'api.url=SUPABASE_URL',
    '--override-name', 'db.url=DATABASE_URL',
    '--override-name', 'auth.service_role_key=SUPABASE_SERVICE_ROLE_KEY',
  ],
  { encoding: 'utf8', shell: process.platform === 'win32' },
);

if (result.status !== 0) {
  process.stderr.write(result.stderr || 'Local Supabase is not running. Run pnpm supabase:start first.\n');
  process.exit(result.status ?? 1);
}

const discovered = Object.fromEntries(
  result.stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#') && line.includes('='))
    .map((line) => {
      const index = line.indexOf('=');
      return [line.slice(0, index), line.slice(index + 1).replace(/^['"]|['"]$/g, '')];
    }),
);

discovered.SUPABASE_URL ||= discovered.API_URL;
discovered.DATABASE_URL ||= discovered.DB_URL;
discovered.SUPABASE_SERVICE_ROLE_KEY ||= discovered.SERVICE_ROLE_KEY;

for (const key of ['SUPABASE_URL', 'DATABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY']) {
  if (!discovered[key]) throw new Error(`Supabase CLI did not report ${key}.`);
}

const secret = () => randomBytes(32).toString('base64url');
const contents = [
  '# Generated by pnpm --filter api env:local. Never commit this file.',
  `DATABASE_URL="${discovered.DATABASE_URL}"`,
  `SUPABASE_URL="${discovered.SUPABASE_URL}"`,
  `SUPABASE_SERVICE_ROLE_KEY="${discovered.SUPABASE_SERVICE_ROLE_KEY}"`,
  'SUPABASE_STORAGE_BUCKET="photos-originals"',
  `CURSOR_SECRET="${secret()}"`,
  `PIN_PEPPER="${secret()}"`,
  `IP_HASH_PEPPER="${secret()}"`,
  'PUBLIC_ORIGIN="http://localhost:5173"',
  'DOCS_ENABLED="true"',
  '',
].join('\n');

await writeFile('.dev.vars', contents, { mode: 0o600 });
console.log('Wrote apps/api/.dev.vars from the running local Supabase stack.');
